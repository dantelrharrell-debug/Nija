function pickPrinciple(d, sig) {
  if (d.stopFired) return "planned_exit";
  if (d.action === "sell" && !d.held) return "know_position";
  if (d.round === 1) return "position_size";
  if (d.action === "buy") return sig === "down" ? "trend_check" : d.stopArmed ? "position_size" : "planned_exit";
  if (d.action === "sell") return "planned_exit";
  if (d.held) return sig === "down" && !d.stopArmed ? "planned_exit" : "same_rule";
  return sig === "up" ? "same_rule" : "patience";
}

function pickText(d, sig) {
  if (d.stopFired) return { explain: EXPLAIN.stop_fired, alt: ALTERNATIVE.stop_fired };
  if (d.action === "sell" && !d.held) return { explain: EXPLAIN.sell_empty, alt: ALTERNATIVE.sell_empty };
  if (d.round === 1) return { explain: EXPLAIN.round1, alt: ALTERNATIVE.round1 };
  const key = d.action === "hold" ? (d.held ? "hold_in" : "hold_cash") : d.action;
  return { explain: EXPLAIN[key][sig], alt: ALTERNATIVE[key][sig] };
}

// Lesson index inside the Academy program = trailing number of the id minus 1 (a test checks this against lessonData).
export const lessonIndexOf = (id) => Number(String(id).split("-").pop()) - 1;
const ADULT_GROUP = /^ages-(18-25|26-45|46-65)$/;

function lessonFor(area, adult) {
  if (adult !== true) return null;
  const l = (REPORT_LESSONS[area] || []).find((x) => ADULT_GROUP.test(x.ageGroup));
  if (!l) return null;
  return { id: l.id, title: l.title, path: `/academy/${l.ageGroup}/lesson/${lessonIndexOf(l.id)}` };
}

// report: output of buildReport. opts.adult must be exactly true (valid adult self-declaration) to get lesson links.
export function buildCoach(report, { adult = false } = {}) {
  if (!report || !Array.isArray(report.challenges)) return null;
  const items = report.challenges.map((c) => ({
    name: c.name,
    decisions: c.decisions.map((d) => {
      const sig = signalOf(d.lastMovePct);
      const pr = PRINCIPLES[pickPrinciple(d, sig)];
      const t = pickText(d, sig);
      return {
        round: d.round,
        action: d.action,
        saw: d.round === 1 ? "No earlier price move yet" : `At the time, ${SIGNAL_TEXT[sig]}${d.held ? ", and you held a position" : ", and you held cash"}`,
        explain: t.explain,
        principle: { name: pr.name, text: pr.text },
        alternative: t.alt,
        lesson: lessonFor(pr.area, adult),
      };
    }),
  }));
  const scored = Object.entries(report.assessments).filter(([, a]) => a.score !== null);
  const weakest = scored.length ? scored.sort((a, b) => a[1].score - b[1].score)[0][0] : "risk";
  return { notice: COACH_NOTICE, focus: AREA_FOCUS[weakest], focusArea: weakest, focusLesson: lessonFor(weakest, adult), items };
}

// Every sentence the coach can ever say (used by wording-review tests).
export function allCoachWording() {
  const out = [COACH_NOTICE];
  for (const v of Object.values(EXPLAIN)) out.push(...(typeof v === "string" ? [v] : Object.values(v)));
  for (const v of Object.values(ALTERNATIVE)) out.push(...(typeof v === "string" ? [v] : Object.values(v)));
  for (const p of Object.values(PRINCIPLES)) out.push(p.name, p.text);
  out.push(...Object.values(AREA_FOCUS), ...Object.values(SIGNAL_TEXT));
  return out;
}

