  const out = [LAB_COACH_NOTICE, ...Object.values(LAB_FOCUS), ...Object.values(ALLOC_LINES), ...Object.values(NEWS_LINES), ...Object.values(POS_LINES), ...Object.values(STOP_REASON), ...Object.values(LAB_PRINCIPLES), ...Object.values(LAB_ALTS)];
  for (const ex of [...LOSS_EXERCISES, ...EMOTION_EXERCISES]) out.push(...Object.values(ex.why));
