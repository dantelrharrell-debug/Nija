function allocLines(exId, w) {
  const r = scoreAllocation(exId, w);
  if (!r.ok) return null;
  if (r.score === null) return { saw: `You invested ${r.invested}%`, explain: ALLOC_LINES.none, extra: [] };
  return {
    saw: `Invested ${r.invested}%, cash ${r.cash}%. ${r.detail}`,
    explain: [r.maxShare > CONCENTRATION_LIMIT ? ALLOC_LINES.conc_high : ALLOC_LINES.conc_ok, r.maxCluster > CLUSTER_LIMIT ? ALLOC_LINES.clus_high : ALLOC_LINES.clus_ok, r.even < 60 ? ALLOC_LINES.even_low : ALLOC_LINES.even_ok].join(" "),
    extra: [ALLOC_LINES.stress],
  };
}

export function buildLabCoach(labRaw) {
  const lab = cleanLabResults(labRaw);
  const items = [];
  for (const ex of ALLOCATION_EXERCISES) {
    const w = lab.allocation[ex.id];
    const l = w && allocLines(ex.id, w);
    if (l) items.push({ id: ex.id, family: "allocation", title: ex.title, saw: l.saw, explain: l.explain, principle: LAB_PRINCIPLES.alloc, alternative: LAB_ALTS.alloc, extra: l.extra });
  }
  for (const it of NEWS_ITEMS) {
    const a = lab.news[it.id];
    const r = a && scoreNews(it.id, a);
    if (!r || !r.ok) continue;
    const resp = NEWS_RESPONSES.find((x) => x.id === a.response).label;
    items.push({
      id: it.id, family: "news", title: it.headline,
      saw: `You called it: ${NEWS_KIND_LABEL[a.kind]}. You chose: ${resp}.`,
      explain: `${r.correct ? NEWS_LINES.right : NEWS_LINES.wrong} This was a ${NEWS_KIND_LABEL[it.kind].toLowerCase()}. ${a.response === "trade_now" ? NEWS_LINES.r_trade_now : r.response >= 90 ? NEWS_LINES.r_ok : NEWS_LINES.r_weak}`,
      principle: LAB_PRINCIPLES.news, alternative: LAB_ALTS.news, extra: ["Clues: " + it.clues.join("; ") + "."],
    });
  }
  for (const ex of POSITION_EXERCISES) {
    const u = lab.position[ex.id];
    const r = u && scorePosition(ex.id, u);
    if (!r || !r.ok) continue;
    const key = r.tooBig ? "too_big" : r.ratio > 2 ? "way_over" : r.ratio > 1 ? "over" : r.ratio < 0.5 ? "tiny" : "within";
    items.push({ id: ex.id, family: "risk", title: ex.title, saw: `You chose ${u} units. Possible loss at the exit: $${r.riskAmount} against a limit of $${r.maxLoss}.`, explain: POS_LINES[key], principle: LAB_PRINCIPLES.pos, alternative: `Alternative: units = loss limit ÷ (entry price − exit price). Here that is at most ${r.limit} units.`, extra: [] });
  }
  for (const ex of LOSS_EXERCISES) {
    const o = lab.loss[ex.id];
    if (o) items.push({ id: ex.id, family: "risk", title: ex.title, saw: `You chose: ${ex.options.find((x) => x.id === o).label}.`, explain: ex.why[o], principle: LAB_PRINCIPLES.loss, alternative: LAB_ALTS.loss, extra: [] });
  }
  for (const ex of STOP_EXERCISES) {
    const o = lab.stop[ex.id];
    if (o) items.push({ id: ex.id, family: "risk", title: ex.title, saw: `You chose: ${ex.options.find((x) => x.id === o).label}.`, explain: STOP_REASON[o], principle: LAB_PRINCIPLES.stop, alternative: LAB_ALTS.stop, extra: [] });
  }
  for (const ex of EMOTION_EXERCISES) {
    const o = lab.emotion[ex.id];
    if (o) items.push({ id: ex.id, family: "discipline", title: ex.title, saw: `You chose: ${ex.options.find((x) => x.id === o).label}.`, explain: ex.why[o], principle: LAB_PRINCIPLES.emo, alternative: LAB_ALTS.emo, extra: [] });
  }
  const sc = scoreLab(lab);
  const scored = Object.entries(sc.areas).filter(([, v]) => v !== null).sort((a, b) => a[1] - b[1] || (a[0] < b[0] ? -1 : 1));
  return { notice: LAB_COACH_NOTICE, focusArea: scored.length ? scored[0][0] : null, focus: scored.length ? LAB_FOCUS[scored[0][0]] : "Answer a few exercises to get a focus point.", items };
}

