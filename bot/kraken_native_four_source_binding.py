"""Construct four existing readers from explicit reviewed owners, never evidence.

The protected root supplies live source objects and authenticates their review.
This module supplies no source publisher, historical backfill, signing key,
approval, clearance, migration or inventory write. Construction does not sample
any source. Existing native observers and the atomic installer retain all proof,
scope, freshness, fencing and completeness checks.
"""
from __future__ import annotations

from collections.abc import Callable, Mapping
from dataclasses import dataclass
import time
from types import MappingProxyType
from typing import Any

from bot.kraken_ledger_evidence import ReviewedLedgerBinding, make_kraken_ledger_evidence_provider
from bot.kraken_operator_authorization import GeneralApprovalBinding, make_general_operator_authorization_provider
from bot.kraken_redis_evidence import FIELDS as REDIS_FIELDS, RedisEvidenceReader, ReviewedBinding, ScopeObservation
from bot.kraken_risk_evidence import make_kraken_risk_limits_provider
from bot.kraken_startup_receipts import StartupReceiptTrust

FIELDS = frozenset({
    "position_ledger_reconciliation", "duplicate_order_fence", "operator_authorization", "risk_limits",
})
ACCOUNT = "platform:kraken"


class NativeFourSourceBindingDenied(ValueError):
    """Fixed non-sensitive denial; never include objects or source payloads."""


@dataclass(frozen=True, eq=False, repr=False)
class ReviewedRedisSource:
    """Existing read-only client and separately authenticated durable coverage."""

    client: Any
    binding: ReviewedBinding


@dataclass(frozen=True, eq=False, repr=False)
class ReviewedOperatorSource:
    """Externally provisioned operator/status keys and signed-record reader."""

    binding: GeneralApprovalBinding
    operator_public_keys: Mapping[str, bytes]
    revocation_public_key: bytes
    read_records: Callable

    def __post_init__(self) -> None:
        if not isinstance(self.operator_public_keys, Mapping):
            raise NativeFourSourceBindingDenied("operator_trust_map_required")
        object.__setattr__(self, "operator_public_keys", MappingProxyType(dict(self.operator_public_keys)))


@dataclass(frozen=True, eq=False, repr=False)
class ReviewedRiskSource:
    """Existing authenticated atomic account snapshot owner; no global substitute."""

    source: Any
    source_id: str
    record_source_ids: Mapping[str, str]
    capital_authority: Any = None
    capital_broker_id: str | None = None
    global_governor: Any = None

    def __post_init__(self) -> None:
        if not isinstance(self.record_source_ids, Mapping):
            raise NativeFourSourceBindingDenied("risk_record_map_required")
        object.__setattr__(self, "record_source_ids", MappingProxyType(dict(self.record_source_ids)))


@dataclass(frozen=True, eq=False, repr=False)
class ReviewedNativeFourSources:
    """Approved live objects and release scope, not self-approving source labels.

    Review must bind the actual Redis client, coverage verifier/scope observer,
    ledger provenance, operator trust roots/record reader and risk publisher to
    this exact canonical runtime and receipt trust. These fields alone do not
    establish that review. Source publishers and current observations remain
    independent prerequisites, not generated by these constructors.
    """

    manager: Any
    strategy: Any
    broker: Any
    service_id: str
    release_id: str
    image_sha256: str
    ledger_binding: ReviewedLedgerBinding
    review_ledger_binding: Callable
    redis: ReviewedRedisSource
    operator: ReviewedOperatorSource
    risk: ReviewedRiskSource


def _validate(
    sources: ReviewedNativeFourSources, *, manager: Any, strategy: Any,
    broker: Any, trust: StartupReceiptTrust, monitoring_category: Any,
) -> None:
    if (type(sources) is not ReviewedNativeFourSources or type(trust) is not StartupReceiptTrust
            or sources.manager is not manager or sources.strategy is not strategy
            or sources.broker is not broker or manager is None or strategy is None
            or broker is None or monitoring_category is None
            or (sources.service_id, sources.release_id, sources.image_sha256)
            != (trust.service_id, trust.release_id, trust.image_sha256)):
        raise NativeFourSourceBindingDenied("canonical_objects_and_release_required")
    owned = getattr(manager, "platform_brokers", None)
    if callable(owned):
        owned = owned()
    matches = ([value for key, value in owned.items() if getattr(key, "value", key) == "kraken"]
               if isinstance(owned, Mapping) else [])
    if len(matches) != 1 or matches[0] is not broker or getattr(broker, "connected", False) is not True:
        raise NativeFourSourceBindingDenied("canonical_broker_changed")
    ledger = sources.ledger_binding
    if (type(ledger) is not ReviewedLedgerBinding or ledger.broker is not broker
            or ledger.account != ACCOUNT or ledger.api_key_sha256 != trust.api_key_sha256
            or ledger.account_sha256 != trust.account_iiban_sha256
            or ledger.provider_id != trust.reviewed_provider_ids["position_ledger_reconciliation"]
            or ledger.monitoring_category is not monitoring_category
            or not callable(sources.review_ledger_binding)):
        raise NativeFourSourceBindingDenied("ledger_binding_mismatch")
    redis = sources.redis
    if (type(redis) is not ReviewedRedisSource or type(redis.binding) is not ReviewedBinding
            or type(redis.binding.expected_scope) is not ScopeObservation
            or redis.binding.expected_scope.account != ACCOUNT
            or redis.binding.expected_scope.api_key_sha256 != trust.api_key_sha256
            or redis.binding.provider_ids != tuple(trust.reviewed_provider_ids[field] for field in REDIS_FIELDS)
            or not callable(getattr(redis.client, "pipeline", None))):
        raise NativeFourSourceBindingDenied("redis_binding_mismatch")
    operator = sources.operator
    if (type(operator) is not ReviewedOperatorSource or type(operator.binding) is not GeneralApprovalBinding
            or operator.binding.account != ACCOUNT
            or operator.binding.account_iiban_sha256 != trust.account_iiban_sha256
            or operator.binding.api_key_sha256 != trust.api_key_sha256
            or operator.binding.release_id != trust.release_id
            or operator.binding.provider_id != trust.reviewed_provider_ids["operator_authorization"]):
        raise NativeFourSourceBindingDenied("operator_binding_mismatch")
    if type(sources.risk) is not ReviewedRiskSource:
        raise NativeFourSourceBindingDenied("risk_binding_required")


def compose_reviewed_native_four_sources(
    *, sources: ReviewedNativeFourSources, review_binding: Callable,
    manager: Any, strategy: Any, broker: Any, trust: StartupReceiptTrust,
    monitoring_category: Any, clock: Callable[[], float] = time.time,
) -> Mapping[str, Callable]:
    """Build actual native readers after exact binding review, without sampling.

    The native Redis reader verifies three fencing observations as one coherent
    read. Only its duplicate-fence result is selected here; existing canonical
    writer/nonce providers remain unchanged. No observation is cached/replayed.
    Review callbacks are separately audited trusted code, not sandboxed here.
    """
    try:
        _validate(sources, manager=manager, strategy=strategy, broker=broker,
                  trust=trust, monitoring_category=monitoring_category)
        if not callable(review_binding) or not callable(clock) or review_binding(sources) is not True:
            raise NativeFourSourceBindingDenied("reviewed_live_binding_required")
        ledger = make_kraken_ledger_evidence_provider(
            sources.ledger_binding, review_binding=sources.review_ledger_binding, clock=clock,
        )
        redis = RedisEvidenceReader(sources.redis.client, sources.redis.binding, clock=clock)

        def duplicate_fence() -> Mapping[str, Any]:
            try:
                rows = redis.collect()
                if not isinstance(rows, Mapping) or set(rows) != set(REDIS_FIELDS):
                    raise NativeFourSourceBindingDenied("native_redis_collection_incomplete")
                return rows["duplicate_order_fence"]
            except Exception:
                raise NativeFourSourceBindingDenied("native_duplicate_evidence_unavailable") from None

        operator = make_general_operator_authorization_provider(
            binding=sources.operator.binding, operator_public_keys=sources.operator.operator_public_keys,
            revocation_public_key=sources.operator.revocation_public_key,
            read_records=sources.operator.read_records, independently_reviewed=True, clock=clock,
        )
        risk = make_kraken_risk_limits_provider(
            sources.risk.source, account_scope=ACCOUNT, approved_api_key_sha256=trust.api_key_sha256,
            reviewed_provider_id=trust.reviewed_provider_ids["risk_limits"],
            reviewed_snapshot_source_id=sources.risk.source_id,
            reviewed_record_source_ids=sources.risk.record_source_ids,
            independently_reviewed=True, capital_authority=sources.risk.capital_authority,
            reviewed_capital_broker_id=sources.risk.capital_broker_id,
            global_governor=sources.risk.global_governor, clock=clock,
        )
        providers = {
            "position_ledger_reconciliation": ledger, "duplicate_order_fence": duplicate_fence,
            "operator_authorization": operator, "risk_limits": risk,
        }
        _validate(sources, manager=manager, strategy=strategy, broker=broker,
                  trust=trust, monitoring_category=monitoring_category)
        if (review_binding(sources) is not True or any(not callable(p) for p in providers.values())
                or len({id(p) for p in providers.values()}) != len(FIELDS)):
            raise NativeFourSourceBindingDenied("reviewed_live_binding_changed")
        def guarded(provider: Callable) -> Callable:
            def observe() -> Mapping[str, Any]:
                try:
                    _validate(sources, manager=manager, strategy=strategy, broker=broker,
                              trust=trust, monitoring_category=monitoring_category)
                    if review_binding(sources) is not True:
                        raise NativeFourSourceBindingDenied("reviewed_live_binding_revoked")
                    row = provider()
                    _validate(sources, manager=manager, strategy=strategy, broker=broker,
                              trust=trust, monitoring_category=monitoring_category)
                    if review_binding(sources) is not True:
                        raise NativeFourSourceBindingDenied("reviewed_live_binding_revoked")
                    return row
                except Exception:
                    raise NativeFourSourceBindingDenied("native_four_source_observation_denied") from None
            return observe

        return MappingProxyType({field: guarded(provider) for field, provider in providers.items()})
    except Exception:
        raise NativeFourSourceBindingDenied("native_four_source_binding_denied") from None
